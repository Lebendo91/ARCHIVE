//! Small helpers shared by the services: identifiers, clock and input validation.

use std::time::{SystemTime, UNIX_EPOCH};

use crate::error::{AppError, AppResult};

/// New identifier: UUID v7, ordered by creation time (ARCHITECTURE.md §6.2).
pub fn new_id() -> String {
    uuid::Uuid::now_v7().to_string()
}

/// Current time in Unix epoch milliseconds (UTC).
pub fn now_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| i64::try_from(duration.as_millis()).unwrap_or(i64::MAX))
        .unwrap_or(0)
}

/// Checks that `value` is an identifier generated by ARCHIVE. Paths are always derived from validated
/// identifiers, which makes path traversal impossible (specification §18.2).
pub fn validate_id(value: &str, field: &str) -> AppResult<()> {
    match uuid::Uuid::parse_str(value) {
        Ok(parsed) if parsed.hyphenated().to_string() == value => Ok(()),
        _ => Err(AppError::InvalidInput(format!(
            "{field} is not a valid identifier"
        ))),
    }
}

/// Trims a user-provided name and checks its length and characters.
pub fn clean_name(value: &str, field: &str, max_chars: usize) -> AppResult<String> {
    let trimmed = value.trim();
    if trimmed.is_empty() {
        return Err(AppError::InvalidInput(format!("{field} is empty")));
    }
    if trimmed.chars().count() > max_chars {
        return Err(AppError::InvalidInput(format!(
            "{field} is longer than {max_chars} characters"
        )));
    }
    if trimmed.chars().any(char::is_control) {
        return Err(AppError::InvalidInput(format!(
            "{field} contains control characters"
        )));
    }
    Ok(trimmed.to_owned())
}

/// Checks the length of a free text (description, content…).
pub fn check_length(value: &str, field: &str, max_chars: usize) -> AppResult<()> {
    if value.chars().count() > max_chars {
        return Err(AppError::InvalidInput(format!(
            "{field} is longer than {max_chars} characters"
        )));
    }
    Ok(())
}

/// Normalised form of a name used to forbid duplicates regardless of case and spacing.
pub fn name_key(name: &str) -> String {
    name.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .to_lowercase()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identifiers_are_valid_uuid_v7_strings() {
        let id = new_id();
        assert!(validate_id(&id, "id").is_ok());
        assert_eq!(
            uuid::Uuid::parse_str(&id)
                .map(|uuid| uuid.get_version_num())
                .ok(),
            Some(7)
        );
    }

    #[test]
    fn identifiers_reject_paths_and_variants() {
        for value in [
            "../etc/passwd",
            "",
            "not-a-uuid",
            "0192F0C4-0000-7000-8000-000000000000",
        ] {
            assert!(
                validate_id(value, "id").is_err(),
                "{value} must be rejected"
            );
        }
    }

    #[test]
    fn names_are_trimmed_and_validated() {
        assert_eq!(
            clean_name("  Études  ", "name", 10).ok().as_deref(),
            Some("Études")
        );
        assert!(clean_name("   ", "name", 10).is_err());
        assert!(clean_name("abcdefghijk", "name", 10).is_err());
        assert!(clean_name("a\u{0}b", "name", 10).is_err());
    }

    #[test]
    fn name_keys_ignore_case_and_spacing_including_accents() {
        assert_eq!(name_key("  ÉTUDES   Supérieures "), "études supérieures");
        assert_eq!(
            name_key("Études supérieures"),
            name_key("études   SUPÉRIEURES")
        );
    }
}
